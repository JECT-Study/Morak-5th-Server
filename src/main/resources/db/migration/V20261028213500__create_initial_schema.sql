CREATE TABLE users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             VARCHAR(255),
    nickname          VARCHAR(20),
    profile_image_url VARCHAR(500),
    status            VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    terms_agreed_at   TIMESTAMP(6),
    marketing_agreed  BOOLEAN     NOT NULL DEFAULT FALSE,
    onboarded_at      TIMESTAMP(6),
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,
    deleted_at        TIMESTAMP(6)
);

CREATE TABLE social_account (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    provider         VARCHAR(20)  NOT NULL,
    provider_user_id VARCHAR(100) NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL
);

CREATE TABLE refresh_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    token_hash CHAR(64)     NOT NULL,
    expires_at TIMESTAMP(6) NOT NULL,
    revoked_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE challenge (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id  BIGINT       NOT NULL,
    title          VARCHAR(50)  NOT NULL,
    description    TEXT,
    category       VARCHAR(30)  NOT NULL,
    invite_code    CHAR(6)      NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'RECRUITING',
    start_date     DATE         NOT NULL,
    end_date       DATE         NOT NULL,
    duration_weeks SMALLINT     NOT NULL,
    capacity       INT          NOT NULL,
    current_count  INT          NOT NULL DEFAULT 0,
    created_at     TIMESTAMP(6) NOT NULL,
    updated_at     TIMESTAMP(6) NOT NULL,
    deleted_at     TIMESTAMP(6),
    visibility     VARCHAR(10)  NOT NULL DEFAULT 'PUBLIC',
    deposit_amount INT          NOT NULL DEFAULT 0
);

CREATE TABLE participation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id        BIGINT       NOT NULL,
    user_id             BIGINT       NOT NULL,
    role                VARCHAR(20)  NOT NULL DEFAULT 'MEMBER',
    status              VARCHAR(20)  NOT NULL,
    apply_message       VARCHAR(200),
    reject_reason_type  VARCHAR(30),
    reject_reason       VARCHAR(200),
    decided_by          BIGINT,
    decided_at          TIMESTAMP(6),
    deposit_amount      INT          NOT NULL DEFAULT 0,
    deposit_status      VARCHAR(20)  NOT NULL DEFAULT 'NONE',
    payment_due_at      TIMESTAMP(6),
    missed_count        INT          NOT NULL DEFAULT 0,
    last_evaluated_date DATE,
    applied_at          TIMESTAMP(6) NOT NULL,
    joined_at           TIMESTAMP(6),
    ended_at            TIMESTAMP(6),
    end_reason          VARCHAR(30)
);

CREATE TABLE certification (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id       BIGINT       NOT NULL,
    participation_id   BIGINT       NOT NULL,
    cert_date          DATE         NOT NULL,
    content            VARCHAR(500),
    link_url           VARCHAR(500),
    status             VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    reject_reason_type VARCHAR(30),
    reject_reason      VARCHAR(200),
    judged_by          BIGINT,
    judged_at          TIMESTAMP(6),
    submit_count       INT          NOT NULL DEFAULT 1,
    submitted_at       TIMESTAMP(6) NOT NULL,
    judge_due_at       TIMESTAMP(6),
    last_reminded_at   TIMESTAMP(6),
    reminder_count     INT          NOT NULL DEFAULT 0,
    updated_at         TIMESTAMP(6) NOT NULL
);

CREATE TABLE certification_image (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certification_id BIGINT       NOT NULL,
    image_key        VARCHAR(300) NOT NULL,
    sort_order       SMALLINT     NOT NULL DEFAULT 0
);

CREATE TABLE certification_reaction (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certification_id BIGINT       NOT NULL,
    user_id          BIGINT       NOT NULL,
    reaction_type    VARCHAR(20)  NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL
);

CREATE TABLE participation_result (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participation_id  BIGINT        NOT NULL,
    challenge_id      BIGINT        NOT NULL,
    user_id           BIGINT        NOT NULL,
    approved_count    INT           NOT NULL,
    total_count       INT           NOT NULL,
    achievement_rate  NUMERIC(5, 2) NOT NULL,
    current_streak    INT           NOT NULL DEFAULT 0,
    max_streak        INT           NOT NULL DEFAULT 0,
    completed         BOOLEAN       NOT NULL DEFAULT FALSE,
    finalized_at      TIMESTAMP(6)  NOT NULL
);

CREATE TABLE medal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(50)  NOT NULL,
    description VARCHAR(200),
    icon_url    VARCHAR(500)
);

CREATE TABLE user_medal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    medal_id     BIGINT       NOT NULL,
    challenge_id BIGINT       NOT NULL,
    earned_at    TIMESTAMP(6) NOT NULL
);

CREATE TABLE chat_message (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id     BIGINT        NOT NULL,
    participation_id BIGINT        NOT NULL,
    content          VARCHAR(1000) NOT NULL,
    created_at       TIMESTAMP(6)  NOT NULL,
    deleted_at       TIMESTAMP(6)
);

CREATE TABLE notification (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT       NOT NULL,
    type              VARCHAR(30)  NOT NULL,
    title             VARCHAR(100) NOT NULL,
    body              VARCHAR(500) NOT NULL,
    target_type       VARCHAR(30),
    target_id         BIGINT,
    dedup_key         VARCHAR(100),
    read_at           TIMESTAMP(6),
    created_at        TIMESTAMP(6) NOT NULL
);

CREATE TABLE push_subscription (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE push_token (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT       NOT NULL,
    channel         VARCHAR(10)  NOT NULL,
    token           VARCHAR(700) NOT NULL,
    p256dh          VARCHAR(255),
    auth            VARCHAR(255),
    user_agent      VARCHAR(255),
    last_success_at TIMESTAMP(6),
    created_at      TIMESTAMP(6) NOT NULL
);

CREATE TABLE point_account (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    balance    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_point_account_balance CHECK (balance >= 0)
);

CREATE TABLE point_transaction (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       BIGINT       NOT NULL,
    type             VARCHAR(20)  NOT NULL,
    reason           VARCHAR(30),
    amount           BIGINT       NOT NULL,
    balance_after    BIGINT       NOT NULL,
    participation_id BIGINT,
    idempotency_key  VARCHAR(100) NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_point_transaction_amount CHECK (amount <> 0)
);

